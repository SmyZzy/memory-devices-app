  '<h3>Системы RAID</h3>
<p>RAID (Redundant Arrays of Inexpensive Disks — избыточный массив недорогих дисков) — технология объединения нескольких дисков в один логический массив для повышения производительности, надёжности или того и другого одновременно. Впервые представлена исследователями (Паттерсон, Гибсон и Кац) из Калифорнийского университета в Беркли в 1987 году.</p>

<h4>RAID 0 — Дисковый массив без отказоустойчивости (Striping)</h4>
<p>Данные разбиваются на блоки, каждый блок записывается на отдельный диск. Несколько операций ввода-вывода выполняются одновременно.</p>
<ul>
<li><strong>Преимущества:</strong> наивысшая производительность; простота реализации; низкая стоимость на единицу объёма.</li>
<li><strong>Недостатки:</strong> не отказоустойчив; отказ одного диска = потеря всех данных массива.</li>
</ul>

<h4>RAID 1 — Зеркалирование (Mirroring)</h4>
<p>Используется два диска, на которые записывается одинаковая информация. При отказе одного остаётся рабочий дубль.</p>
<ul>
<li><strong>Преимущества:</strong> простота реализации; простота восстановления (копирование); высокое быстродействие при чтении.</li>
<li><strong>Недостатки:</strong> высокая стоимость (100% избыточность); невысокая скорость записи.</li>
</ul>

<h4>Архитектура RAID</h4>
<p>Рассмотрим N дисков (N — чётное число), каждый из M блоков. Диски могут подключаться к одному или нескольким каналам передачи данных. Использование большего количества каналов увеличивает пропускную способность системы.</p>',
