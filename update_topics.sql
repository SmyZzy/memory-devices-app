  '<h3>Кеш-память (Cache Memory)</h3>
<p>Кеш-память — это высокоскоростная память произвольного доступа, используемая процессором компьютера для временного хранения информации. Она увеличивает производительность, поскольку хранит наиболее часто используемые данные и команды «ближе» к процессору, откуда их можно быстрее получить.</p>

<h4>Методы записи информации в кеш</h4>
<ul>
<li><strong>Write-back (обратная запись)</strong> — запись данных производится сначала в кеш, а затем, при наступлении определённых условий, и в ОЗУ. Более быстрый метод, но требует дополнительной логики отслеживания изменённых данных.</li>
<li><strong>Write-through (сквозная запись)</strong> — запись данных производится одновременно в ОЗУ и в кеш. Более надёжный, но медленнее.</li>
</ul>

<h4>Архитектура ассоциативности кэширования</h4>
<ul>
<li><strong>Кеш с прямым отображением</strong> — определённый участок кеша отвечает за определённый участок ОЗУ. Простая реализация, но возможны конфликты.</li>
<li><strong>Полностью ассоциативный кеш</strong> — любой участок кеша может ассоциироваться с любым участком ОЗУ. Максимальная гибкость, но высокая стоимость поиска.</li>
<li><strong>Смешанный кеш (наборно-ассоциативный)</strong> — компромиссный вариант: кеш разделён на наборы (sets), и данные могут размещаться в любом слоте внутри своего набора. Используется в большинстве современных процессоров.</li>
</ul>',
