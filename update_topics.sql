  'Тема 1. Оперативная память',
  '<h3>Оперативная память (ОЗУ, RAM)</h3>
<p>Оперативная память — один из важнейших компонентов системы, необходима для работы операционной системы и приложений, для обработки и временного хранения данных. ОЗУ не позволяет хранить информацию после выключения питания, но работает намного быстрее жестких дисков. Любая программа сначала загружается с жесткого диска в оперативную память и лишь затем начинает работу.</p>

<h4>Основные понятия</h4>
<p>Оперативная память может обозначаться как <strong>ОЗУ</strong> (оперативное запоминающее устройство) или <strong>RAM</strong> (Random Access Memory — память с произвольным доступом). Выполняется в виде отдельных модулей, состоящих из нескольких чипов памяти, которые устанавливаются в соответствующие разъемы на системной плате.</p>

<h4>Организация чипов памяти</h4>
<p>Каждый чип памяти — это матрица из миллионов миниатюрных конденсаторов, являющихся элементарными ячейками памяти. Конденсаторы могут находиться в заряженном (1) или разряженном (0) состоянии. Кроме конденсаторов, чип содержит схемы управления чтением, записью и <strong>регенерацией данных</strong> — для восстановления заряда конденсаторов, поскольку со временем они самопроизвольно разряжаются.</p>

<h4>Блочная организация памяти</h4>
<p>Емкость основной памяти слишком велика для реализации на одной ИМС. Необходимость объединения нескольких ИМС ЗУ возникает, когда разрядность ячеек меньше разрядности слов ВМ. Увеличение разрядности реализуется за счет объединения адресных входов ИМС ЗУ. Полученную совокупность микросхем называют <strong>модулем памяти</strong>. Один или несколько модулей образуют <strong>банк памяти</strong>.</p>

<h4>Расслоение памяти</h4>
<p>Блочное построение памяти позволяет сократить время доступа благодаря потенциальному параллелизму. Большей скорости доступа можно достичь за счет одновременного доступа ко многим банкам памяти. Методика называется <strong>расслоением памяти</strong>. В её основе — <strong>чередование адресов</strong> (address interleaving), заключающееся в изменении системы распределения адресов между банками памяти.</p>

<h4>Организация микросхем памяти</h4>
<p>ИМС памяти организованы в виде матрицы ячеек. Каждый запоминающий элемент (ЗЭ) способен хранить один бит и имеет два стабильных состояния (0 и 1). Реализуется <strong>координатный принцип адресации</strong>: адрес разделяется на адрес строки и адрес столбца. Запоминающие элементы на пересечении горизонтальной и вертикальной линии образуют <strong>строку (row)</strong> и <strong>столбец (column)</strong>. Совокупность ЗЭ и логических схем выбора называют <strong>ядром микросхемы памяти</strong>.</p>',
